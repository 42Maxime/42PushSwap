#include "../include/push_swap.h"

int	ft_flag_nbr(int ac, char **av)
{
	int	i;

	i = 0;
	while (ac > 1)
	{
		if (ft_isd(av[ac][1]) == 1)
			i += 1;
		ac--;
	}
	return (i);
}
