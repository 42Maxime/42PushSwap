#include "../include/push_swap.h"

int	ft_flag(int ac, char **av)
{
	int	i;

	i = 0;
	if (av[1] == '-')
		return (1);
	if (ft_isd(av[1]) == 1)
	{
		i += 1;
	}
	
	ac--;
	return (0);
}